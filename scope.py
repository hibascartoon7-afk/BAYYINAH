# -*- coding: utf-8 -*-
"""
كشف ما يقع خارج وظيفة «بيّنة»، حتى لا تُعرض أحاديث عشوائية جوابًا عليه:
  - السؤال العام (لماذا…؟ هل…؟ ما معنى…؟ ترجم…)
  - الآية القرآنية بين القوسين ﴿ ﴾ (لا «قال الله تعالى»، فهي تَرِد في الأحاديث القدسية)
  - النص غير العربي

لا يُستدعى إلا بعد أن يتبيّن أن النص لم يوجد بلفظه في مصادرنا،
فالحديث الموجود بلفظه يُعرض دائمًا ولو جاء بصيغة سؤال («هل تدرون ما المفلس؟»).
"""
import difflib
import re

from normalize import normalize

# بداية السؤال، بصيغتها بعد normalize (ى→ي، أ→ا)
_QUESTION_START = re.compile(
    r"^(?:لماذا|ليش|ليه|هل|كيف|متي|اين|ماذا|شو|ما\s+معني|ما\s+الفرق|ما\s+حكم|ما\s+هو|ما\s+هي|"
    r"اشرح|اشرحي|ترجم|ترجمي|عرف|عرفي|وضح|وضحي|اعطني|اعطيني)\b"
)
# علامات أن النص طلب تحقق من حديث، فلا يُعدّ خارج الوظيفة أبدًا.
# (لا نعدّ ﷺ وحدها علامة: «هل القرآن من تأليف محمد ﷺ؟» سؤال عام لا طلب تحقق.)
# يُقبل قبل الكلمة حرفان ملتصقان (و ف ب ل ك) و«ال»: «الحديث»، «للنبي»، «والأحاديث».
_HADITH_CUE = re.compile(
    r"\b[وفبلك]{0,2}(?:ال)?(?:حديث\w*|احاديث|نبي|رسول\s+الله|قال\s+الله|يقول\s+الله|"
    r"صحيح\w*|صحه|درجه\w*|ضعيف\w*|موضوع\w*|مكذوب|ثابت\w*|يثبت|سند\w*|اسناد\w*|رواه|روي)\b"
)
_ARABIC = re.compile(r"[\u0621-\u064A]")
_LATIN = re.compile(r"[A-Za-z]")

# إن كان أقرب نص معروض يشترك مع ما كتبه المستخدم في نصف كلماته الدالّة فأكثر، فهو على الأرجح حديث بلفظ محرّف لا سؤال عام
_CLOSE_ENOUGH = 0.5

# لا تُحتسب في المقارنة: الصلاة على النبي ﷺ (يحوّلها normalize إلى أربع كلمات تتكرر في أحاديث كثيرة)،
# وأدوات الربط والسؤال. وإلا بدا سؤال عام مثل «هل القرآن من تأليف محمد ﷺ؟» قريبًا من أي حديث فيه الصلاة على النبي.
_SALAWAT = re.compile(r"صلي الله عليه وسلم")
_STOP = {"هل", "من", "في", "علي", "عن", "الي", "ما", "ماذا", "لماذا", "كيف", "متي", "اين", "ان", "او", "و",
         "لا", "لم", "لن", "قد", "ثم", "هذا", "هذه", "ذلك", "تلك", "الذي", "التي", "كل", "مع", "بين", "هو", "هي",
         "كان", "يا", "قال", "شو", "ليش", "ليه"}


def _content_words(text: str) -> list:
    return [w for w in _SALAWAT.sub(" ", normalize(text)).split() if w not in _STOP]


def _content_overlap(user_text: str, other: str) -> float:
    """نسبة كلمات المستخدم الدالّة الموجودة في النص الآخر (تُقبل الكلمة القريبة جدًا: تدرون/أتدرون)."""
    u, o = _content_words(user_text), _content_words(other)
    if not u or not o:
        return 0.0
    hit = sum(1 for w in u if any(difflib.SequenceMatcher(None, w, x).ratio() >= 0.8 for x in o))
    return hit / len(u)

SCOPE_MSG = ("«بيّنة» تتحقق من نصوص الأحاديث المنتشرة: الصق الحديث كما وصلك، فنعرض لك مصدره "
             "وأقوال العلماء فيه. أما هذا فسؤال عام لا تجيب عنه الأداة، ويُرجع فيه إلى أهل العلم "
             "والمصادر الموثوقة.")
QURAN_MSG = ("يبدو أن النص يتضمن آية قرآنية. «بيّنة» تتحقق من الأحاديث النبوية، ولا تتضمن مصادرها نص القرآن الكريم؛ "
             "فراجع المصحف أو مصدرًا قرآنيًا موثوقًا للتحقق من لفظ الآية.")
LANG_MSG = ("تعمل «بيّنة» حاليًا على النصوص العربية. الصق نص الحديث بالعربية كما وصلك، "
            "فنعرض لك مصدره وأقوال العلماء فيه.")


def out_of_scope(user_text: str, related: list) -> str:
    """تُرجع رسالة إن كان النص خارج وظيفة الأداة، وإلا تُرجع نصًا فارغًا."""
    raw = (user_text or "").strip()
    norm = normalize(raw)

    # 1) نص غير عربي في معظمه
    if len(_LATIN.findall(raw)) > len(_ARABIC.findall(raw)):
        return LANG_MSG

    # 2) آية قرآنية: لا نحكم بذلك إلا إذا جاءت بين القوسين ﴿ ﴾.
    #    («قال الله تعالى» تَرِد في الأحاديث القدسية، فلا تكفي علامةً على القرآن.)
    if "﴿" in raw:
        return QURAN_MSG

    # 3) طلب تحقق من حديث: يُبحث عنه دائمًا، ولو جاء بصيغة سؤال
    if _HADITH_CUE.search(re.sub(r"\b([وفبك]?)لل", r"\1لال", norm)):
        return ""

    # 4) سؤال عام — إلا إن كان أقرب نص معروض قريبًا جدًا من لفظه، فهو حديث محرّف لا سؤال
    is_question = bool(_QUESTION_START.search(norm)) or raw.endswith(("؟", "?"))
    if is_question:
        best = max((_content_overlap(raw, c.get("matn", "")) for c in related), default=0)
        if best < _CLOSE_ENOUGH:
            return SCOPE_MSG
    return ""